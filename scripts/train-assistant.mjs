import fs from 'node:fs/promises';
import {knowledge} from '../assistant-knowledge.js';
import {trainingExamples, unknownExamples} from '../assistant-training-data.js';
import {features} from '../assistant-nlu.js';

// Deterministic supervised multinomial logistic regression. No customer data or network.
const labels = [...knowledge.map(e => e.id), 'unknown'];
const samples = knowledge.flatMap(entry => [...new Set([...entry.examples, ...trainingExamples[entry.id]])].map(text => ({text,label:entry.id})));
samples.push(...unknownExamples.map(text => ({text,label:'unknown'})));
const vocabulary = [...new Set(samples.flatMap(sample => features(sample.text).map(([key]) => key)))].sort();
const lookup = new Map(vocabulary.map((key,i) => [key,i]));
const dataset = samples.map(({text,label}) => ({y:labels.indexOf(label), x:features(text).map(([key,value]) => [lookup.get(key),value])}));
const weights = vocabulary.map(() => new Float64Array(labels.length)), biases = new Float64Array(labels.length);
for (let epoch = 0; epoch < 180; epoch++) {
  const rate = .65 / (1 + epoch / 100);
  // A coprime stride prevents grouping updates by label and makes rebuilding reproducible.
  for (let offset = 0; offset < dataset.length; offset++) {
    const {x,y} = dataset[(offset * (dataset.length - 1) + epoch) % dataset.length];
    const logits = Array.from(biases);
    for (const [i,value] of x) for (let k = 0; k < labels.length; k++) logits[k] += weights[i][k] * value;
    const max = Math.max(...logits), probabilities = logits.map(logit => Math.exp(logit-max)), total = probabilities.reduce((a,b) => a+b,0);
    for (let k = 0; k < labels.length; k++) {
      const gradient = probabilities[k]/total - Number(k === y);
      biases[k] -= rate * gradient;
      for (const [i,value] of x) weights[i][k] -= rate * (gradient * value + .0001 * weights[i][k]);
    }
  }
}
const round = value => Number(value.toFixed(5));
const model = {version:1, algorithm:'multinomial logistic regression', samples:samples.length, labels, biases:Array.from(biases,round), weights:Object.fromEntries(vocabulary.map((key,i) => [key,Array.from(weights[i],round)]))};
await fs.writeFile(new URL('../assistant-model.js',import.meta.url), `// Generated by npm run train:assistant. Do not edit weights manually.\nexport const model = ${JSON.stringify(model)};\n`);
console.log(`Trained ${labels.length-1} courier intents + unknown on ${samples.length} labelled examples; ${vocabulary.length} features.`);
