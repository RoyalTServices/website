import fs from 'node:fs/promises';
import {createRateWorkbook,parseRateWorkbook} from '../rate-workbook.mjs';
const root=new URL('../',import.meta.url);
const data=JSON.parse(await fs.readFile(new URL('data/rates.json',root),'utf8'));
const bytes=await createRateWorkbook(data);
await parseRateWorkbook(bytes);
await fs.writeFile(new URL('assets/royal-t-price-list-template.xlsx',root),bytes);
await fs.writeFile(new URL('rate-seed.mjs',root),`// Generated by scripts/prepare-rate-template.mjs; bootstrap only when Storage has no active list.\nexport const initialRateWorkbook = '${bytes.toString('base64')}';\n`);
console.log('Prepared validated price-list template and initial Storage seed.');
